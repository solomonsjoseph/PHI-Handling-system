# Precomputed upper-cased set for O(1) case-insensitive lookup
_DMY_UPPER: frozenset[str] = frozenset(v.upper() for v in DMY_VARIABLES)


def is_dmy_variable(field_name: str) -> bool:
    """Return True if *field_name* is known to use D/M (day-first) date order.

    Checks against the canonical ``DMY_VARIABLES`` frozenset defined in
    this module.  The comparison is **case-insensitive** so that column
    name variants (e.g. ``ic_visdat``, ``IC_VISDAT``, ``Ic_VisDat``) all
    resolve identically.
    """
    return field_name.upper() in _DMY_UPPER


def _disambiguate_locale(value: str, *, declared_locale: str | None = None) -> str | None:
    """Attempt to determine whether *value* is in DMY or MDY format.

    Args:
        value: A separator-delimited date string like ``"28/05/2014"``,
               ``"28-05-2014"``, or ``"05.28.2014"``.  Only the first two
               numeric components (before the year) are inspected.
        declared_locale: If provided (``"DMY"`` or ``"MDY"``), return it
                         immediately without inspecting *value*.

    Returns:
        ``"DMY"`` if the first component must be the day,
        ``"MDY"`` if the second component must be the day, or
        ``None`` if both components are ≤ 12 (genuinely ambiguous).

    Raises:
        ValueError: If both numeric components exceed 12 (impossible as either
                    month or day).
    """
    if declared_locale is not None:
        return declared_locale

    # Accept /, -, or . as separator (ISO YYYY-MM-DD is caught by _ISO_RE first).
    m = _SEP_RE.match(value.strip())
    if not m:
        return None

    # Groups: (1)=first_component, (2)=sep, (3)=second_component, (4)=year
    g1, g2 = int(m.group(1)), int(m.group(3))

    if g1 > 12 and g2 > 12:
        raise ValueError(f"Invalid date string: {value!r} (both components exceed 12)")

    if g1 > 12:
        # First component cannot be a month → it must be the day → DMY
        return "DMY"
    if g2 > 12:
        # Second component cannot be a month → it must be the day → MDY
        return "MDY"

    # Both ≤ 12: cannot determine locale from value alone
    return None


# ============================================================================
# PHI-safe value masking (for logs and exception messages only)
# ============================================================================


def _mask_date_value(value: str) -> str:
    """Return a PHI-safe shape of *value* for logs and error messages.

    Digits → ``9``, ASCII letters → ``X``, separator characters kept.

    Note: mirrors ``scripts.security.phi_patterns.mask_date_shape``.  A direct
    import is not possible because ``scripts.security.__init__`` imports
    ``phi_scrub``, which imports ``scripts.extraction.io``, creating a circular
    dependency.  If the masking contract changes, update both implementations.
    """
    result: list[str] = []
    for ch in value:
        if ch.isdigit():
            result.append("9")
        elif ch.isascii() and ch.isalpha():
            result.append("X")
        else:
            result.append(ch)
    return "".join(result)


